import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=name=>fs.readFileSync(new URL('../'+name,import.meta.url),'utf8');
const exp=read('assets/export.js'), app=read('assets/app.js'), html=read('index.html');
assert.ok(exp.includes("kind==='pdf'"));
assert.ok(exp.includes('openOfficialPdf()'));
assert.ok(exp.includes('validateAndPrint()'));
assert.ok(!exp.includes('generatePDF()'));
assert.ok(app.includes('async function prepareAndPrint()')&&app.includes('window.print()'));
assert.ok(html.includes('Mesmo laudo da impressão'));
assert.equal(JSON.parse(read('version.json')).version,'1.4.8');
assert.ok(app.includes("APP_VERSION = '1.4.8'"));
assert.ok(read('service-worker.js').includes('shell-v1.4.8'));
console.log('OK: PDF canônico via impressão nativa e versionamento 1.4.8.');
