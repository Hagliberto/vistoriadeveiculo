import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = filename => fs.readFileSync(new URL('../'+filename,import.meta.url),'utf8');
const exp=read('assets/export.js'), app=read('assets/app.js'), html=read('index.html');
const start=exp.indexOf("if(kind==='pdf')");
const end=exp.indexOf("if(kind==='png')",start);
assert.ok(start>=0 && end>start);
const handler=exp.slice(start,end);
assert.ok(handler.includes('validateAndPrint()'), 'salvar PDF deve usar impressão nativa');
assert.ok(!handler.includes('generatePDF()')&&!handler.includes('download('), 'não pode gerar versão raster no botão PDF');
assert.ok(app.includes('async function prepareAndPrint()')&&app.includes('window.print()'));
assert.ok(html.includes('Mesmo laudo da impressão'));
assert.ok(exp.includes('await navigator.share({files:[file]'), 'compartilhamento mantido');
assert.equal(JSON.parse(read('version.json')).version,'1.4.5');
assert.ok(app.includes("APP_VERSION = '1.4.5'"));
assert.ok(read('service-worker.js').includes('shell-v1.4.5'));
console.log('OK: PDF usa o mesmo pipeline A4 da impressão; compartilhamento preservado; versão 1.4.5.');
