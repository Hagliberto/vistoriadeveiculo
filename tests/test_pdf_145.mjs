assert.ok(!html.includes('data-export-format="png"'));
assert.ok(app.includes("APP_VERSION = '1.5.8'"));
assert.ok(r('service-worker.js').includes('shell-v1.5.8'));
console.log('OK: HTML A4 canônico e versão 1.5.8.');
