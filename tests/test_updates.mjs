import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const base = path.resolve(import.meta.dirname, '..');
const app = fs.readFileSync(path.join(base,'assets/app.js'),'utf8');
const sw = fs.readFileSync(path.join(base,'service-worker.js'),'utf8');
const html = fs.readFileSync(path.join(base,'index.html'),'utf8');
const version = JSON.parse(fs.readFileSync(path.join(base,'version.json'),'utf8')).version;
const actual = app.match(/const APP_VERSION = '([^']+)'/)[1];
assert.equal(actual, version);
assert.ok(sw.includes(`vistoria-veicular-shell-v${version}`));
assert.ok(sw.includes("endsWith('/version.json')"));
assert.ok(sw.includes("event.data?.type === 'SKIP_WAITING'"));
const installCode = sw.slice(sw.indexOf("self.addEventListener('install'"), sw.indexOf("self.addEventListener('message'"));
assert.ok(!installCode.includes('skipWaiting'));
assert.ok(html.includes('id="btn-apply-update"'));
assert.ok(html.includes('id="btn-check-updates"'));
assert.ok(html.includes('id="app-update-notice"'));
assert.ok(app.includes('await saveInFlight'));
const fn = app.slice(app.indexOf('function isNewerVersion('), app.indexOf('function setUpdateSettingsMessage('));
assert.ok(fn);
const compare = vm.runInNewContext(`${fn}; isNewerVersion`);
assert.equal(compare('1.5.5', '1.4.0'), true);
assert.equal(compare('1.4.1', '1.4.0'), true);
assert.equal(compare('1.4.0', '1.4.0'), false);
assert.equal(compare('1.3.9', '1.4.0'), false);
assert.equal(compare('1.4.0-beta', '1.4.0'), false);
console.log('OK: versões, botão de atualização, SW aguardando confirmação, salvamento e política de cache.');
