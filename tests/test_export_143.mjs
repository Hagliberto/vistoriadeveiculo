import assert from 'node:assert/strict';
import fs from 'node:fs';
const r=file=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8');
const html=r('index.html'), exp=r('assets/export.js'), app=r('assets/app.js'), css=r('assets/print-and-custom.css');
assert.ok(html.includes('data-open-export') && html.includes('id="export-modal"'));
assert.ok(html.includes('data-export-format="pdf"') && !html.includes('data-export-format="print"'));
assert.ok(!html.includes('data-export-format="png"'));
assert.ok(html.includes('export-content-options'));
assert.ok(exp.includes('applyPrintSelection()') && exp.includes('validateAndPrint()'));
assert.ok(app.includes('async function prepareAndPrint()'));
assert.ok(css.includes('body.print-selective.print-omit-checklist'));
assert.ok(r('service-worker.js').includes("'./assets/export.js'"));
assert.equal(JSON.parse(r('version.json')).version,'1.5.9');
console.log('OK: exportação seletiva, sem PNG, laudo A4 único v1.5.9.');
